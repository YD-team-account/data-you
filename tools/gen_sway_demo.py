#!/usr/bin/env python3
"""좌우 흔들림 시연용 차량 신호 프로필을 만든다.

출력
  sample-data/sway_demo.csv  : 엔진 검증용 (요레이트는 앱과 같은 자전거 모델로 핸들 각도에서 계산)
  tools/sway_demo.sh         : 에뮬레이터 안에서 실행하는 주입 스크립트 (dumpsys IVehicle --set)

구간
  0~12s   서서히 출발 → 시속 40km
  12~17s  직진
  17~62s  연속 커브: 핸들 ±50도, 주기 6초(0.17Hz, 멀미 대역 0.1~0.5Hz)
  62~70s  직진, 시속 60km까지 가속
  72~77s  왼쪽 깜빡이 + 급차선변경 (핸들 +45 → -45 → 0, 각 1.2초)
  77~85s  직진
  85~97s  서서히 감속 → 정차 (정차 카드 확인)
"""
import math, os

DT = 0.2
AMP, PERIOD = 55, 5.0   # 핸들 진폭(도), 주기(초). 좌우 가속 최대 약 2.8m/s² → 개별 '급회전' 기준(3.0) 아래
STEER_RATIO, WHEELBASE, DEADBAND = 14.5, 2.9, 1.5
SPEED, STEER, SIGNAL = 0x11600207, 0x11600209, 0x11400408  # AAOS property ids
SIG = {"OFF": 0, "RIGHT": 1, "LEFT": 2}

def profile():
    t, v = 0.0, 0.0
    rows = []
    while t <= 100.0:
        steer, sig = 0.0, "OFF"
        if t < 12: v = 11.11 * t / 12
        elif t < 17: v = 11.11
        elif t < 62:
            v = 11.11
            steer = AMP * math.sin(2 * math.pi * (t - 17) / PERIOD)
        elif t < 70: v = 11.11 + (16.67 - 11.11) * (t - 62) / 8
        elif t < 85:
            v = 16.67
            if 72 <= t < 77: sig = "LEFT"
            if 73 <= t < 74.2: steer = 45
            elif 74.2 <= t < 75.4: steer = -45
        elif t < 97: v = 16.67 * (1 - (t - 85) / 12)
        else: v = 0.0
        rows.append((round(t, 1), max(v, 0.0), steer, sig))
        t += DT
    return rows

def yaw(v, deg):
    if abs(deg) < DEADBAND or v <= 0: return 0.0
    return v * math.tan(math.radians(deg / STEER_RATIO)) / WHEELBASE

def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    rows = profile()
    with open(os.path.join(root, "sample-data", "sway_demo.csv"), "w", newline="\n") as f:
        f.write("timestamp_ms,speed_mps,yaw_rate_rad_s,heading_deg,brake,turn_signal\n")
        for t, v, s, sig in rows:
            f.write(f"{int(t*1000)},{v:.3f},{yaw(v, s):.5f},,,{sig}\n")
    lines = ["#!/system/bin/sh", "# generated by tools/gen_sway_demo.py — runs inside the emulator (root)",
             "S=android.hardware.automotive.vehicle.IVehicle/default",
             "set_f() { dumpsys $S --set $1 -f $2 >/dev/null 2>&1; }",
             "set_i() { dumpsys $S --set $1 -i $2 >/dev/null 2>&1; }",
             f"set_i {SIGNAL} 0", f"set_f {STEER} 0", f"set_f {SPEED} 0", "echo start"]
    last_sig = "OFF"
    for t, v, s, sig in rows:
        if sig != last_sig:
            lines.append(f"set_i {SIGNAL} {SIG[sig]}")
            last_sig = sig
        lines.append(f"set_f {SPEED} {v:.2f}; set_f {STEER} {s:.1f}; sleep {DT}")
        if t in (12.0, 17.0, 62.0, 72.0, 85.0, 97.0):
            lines.append(f"echo t={t:.0f}s")
    lines += [f"set_i {SIGNAL} 0", f"set_f {STEER} 0", f"set_f {SPEED} 0", "echo done"]
    with open(os.path.join(root, "tools", "sway_demo.sh"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(rows)} steps")

if __name__ == "__main__":
    main()
